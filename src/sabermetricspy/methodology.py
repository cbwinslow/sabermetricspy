"""Reference-status audit data: how each metric and model compares with its published method.

The audit lives in the bundled `data/methodology.yaml` (data, not code: ADR-0012). The registry applies
it to every `MetricSpec` at registration, and `docs/METHODOLOGY.md` is rendered from it so the
document and the registry cannot disagree.
"""

from __future__ import annotations

from functools import lru_cache
from importlib import resources
from typing import Any

import yaml
from pydantic import BaseModel, ConfigDict

from sabermetricspy.types.enums import ReferenceStatus


class MethodologyEntry(BaseModel):
    """Audit result for one metric or model."""

    model_config = ConfigDict(frozen=True)

    status: ReferenceStatus
    source_url: str = ""
    note: str = ""


@lru_cache(maxsize=1)
def _load() -> dict[str, dict[str, MethodologyEntry]]:
    path = resources.files("sabermetricspy").joinpath("data/methodology.yaml")
    raw: dict[str, Any] = yaml.safe_load(path.read_text(encoding="utf-8"))
    return {
        section: {
            name: MethodologyEntry.model_validate(entry) for name, entry in raw[section].items()
        }
        for section in ("metrics", "models")
    }


def metric_entries() -> dict[str, MethodologyEntry]:
    """Audit entries for registered metrics, keyed by canonical metric name."""
    return dict(_load()["metrics"])


def model_entries() -> dict[str, MethodologyEntry]:
    """Audit entries for estimators and frameworks that are not registry metrics (WAR, Marcel, ...)."""
    return dict(_load()["models"])


def render_markdown() -> str:
    """Render docs/METHODOLOGY.md from the audit data and the registry."""
    from sabermetricspy.registry import REGISTRY
    from sabermetricspy.types.enums import Metric

    metrics = metric_entries()
    specs = {s.name: s for s in REGISTRY.all_specs() if isinstance(s.metric, Metric)}
    lines = [
        "# Methodology Audit",
        "",
        "Generated by `uv run python -m sabermetricspy.methodology > docs/METHODOLOGY.md` from "
        "`src/sabermetricspy/data/methodology.yaml`; a test fails if this file and the registry disagree.",
        "",
        "Status key: **matches** (agrees with the published method and, where a published value was "
        "available, with published numbers), **approximate** (same idea, differs in a documented way), "
        "**divergent** (documented formula or behavior differs from the published method), "
        "**unverified** (not yet audited against a primary source).",
        "",
        "| Metric | Name | Category | Status | Source | Note |",
        "| :-- | :-- | :-- | :-- | :-- | :-- |",
    ]
    for name in sorted(specs, key=lambda n: (str(specs[n].category), n)):
        spec = specs[name]
        entry = metrics[name]
        source = f"[source]({entry.source_url})" if entry.source_url else ""
        lines.append(
            f"| `{name}` | {spec.display_name} | {spec.category!s} | {entry.status.value} | {source} | "
            f"{entry.note.replace('|', '/')} |"
        )
    lines += [
        "",
        "## Models and frameworks",
        "",
        "| Model | Status | Source | Note |",
        "| :-- | :-- | :-- | :-- |",
    ]
    for name, entry in sorted(model_entries().items()):
        source = f"[source]({entry.source_url})" if entry.source_url else ""
        lines.append(
            f"| `{name}` | {entry.status.value} | {source} | {entry.note.replace('|', '/')} |"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import sys

    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    sys.stdout.write(render_markdown())
